import { z } from 'zod';
import { parseCidr } from '@repo/vpn-sdk/cidr';
import { Domain, Ipv4, MAX_DNS_DOMAINS, MAX_DNS_SERVERS } from '@repo/vpn-sdk';

/**
 * Wire protocol between the app (as the user) and the privileged network
 * helper: one JSON object per line over a loopback TCP connection.
 *
 * A session starts with a mutual challenge-response so the secret never
 * crosses the wire and the app never talks to an impostor on the port:
 *   app → hello { nonce }            helper → { challenge, proof: HMAC(key, helperProof(nonce)) }
 *   app → auth { proof: HMAC(key, appProof(challenge)) }   helper → { ok }
 * `key` is derived from the app's random token (core/helper-crypto). The token
 * never leaves the app; the helper keeps the key in a root-only file.
 *
 * The authenticated connection is the active session (newest wins). When it
 * closes, the helper removes every route and DNS entry it added, so a crashed
 * app can't leave routes behind. The helper accepts only these commands and
 * validates every field — it never takes raw config or paths.
 */

/** Bumped whenever the protocol or the helper's behavior changes; the app reinstalls a mismatching helper. */
export const HELPER_VERSION = 9;

/** launchd label / service name of the installed helper. */
export const HELPER_LABEL = 'dev.multi-vpn-client.helper';

/** The helper's root-only working directory (the generated sing-box config holds SOCKS credentials). */
export const HELPER_WORK_DIR = '/var/run/multi-vpn-client-helper';

/** Loopback port the helper listens on. */
export const HELPER_PORT = 47821;

/** First line of every /etc/resolver entry the helper writes; anything without it isn't ours and is never touched. */
export const RESOLVER_MARK = '# multi-vpn-client';

/** Requests larger than this are rejected before parsing. */
export const MAX_HELPER_LINE = 256 * 1024;

/** What the app shows about the installed helper. */
export type HelperState = 'ready' | 'not-installed' | 'needs-update' | 'not-responding' | 'unsupported';

/** Messages each side signs, distinct so a proof from one direction can't be replayed in the other. */
export const helperProofMessage = (nonce: string) => `mvpn-helper:${nonce}`;
export const appProofMessage = (nonce: string) => `mvpn-app:${nonce}`;

const Canonical = z.string().superRefine((value, ctx) => {
  const parsed = parseCidr(value);
  if (!parsed.ok) ctx.addIssue(parsed.error);
  else if (parsed.cidr !== value) ctx.addIssue('Expected a canonical CIDR like 10.20.0.0/16');
});

/** Credentials, ids and nonces are generated by the app, so only a narrow charset is allowed. */
const Token = z.string().regex(/^[A-Za-z0-9_-]{1,128}$/, 'Unexpected characters');
export const Hex64 = z.string().regex(/^[0-9a-f]{64}$/);

const VpnId = z.string().regex(/^[A-Za-z0-9-]{1,64}$/, 'Unexpected characters');

export const VpnTunnelInput = z.strictObject({
  vpnId: VpnId,
  /** Host port published by the VPN's container for its SOCKS server. */
  port: z.number().int().min(1024).max(65535),
  username: Token,
  password: Token,
  /** Compiled, disjoint CIDRs for this VPN. */
  cidrs: z.array(Canonical).max(4096),
  /** First server is used for `domains`; nothing is routed when there is no server. */
  dns: z.strictObject({ servers: z.array(Ipv4).max(MAX_DNS_SERVERS), domains: z.array(Domain).max(MAX_DNS_DOMAINS) }),
});
/** One connected VPN, as the host routing engine sees it. */
export type VpnTunnel = z.infer<typeof VpnTunnelInput>;

/** A domain route for a connected VPN; matches the domain and its subdomains. */
export const DomainRouteInput = z.strictObject({ vpnId: VpnId, domain: Domain });

/**
 * Where the routing engine reports live connections (its Clash API), for the app's traffic views:
 * loopback only, behind a per-session secret.
 */
export const StatsEndpointInput = z.strictObject({ port: z.number().int().min(1024).max(65535), secret: Token });
export type StatsEndpoint = z.infer<typeof StatsEndpointInput>;

/**
 * Everything the host routes: connected VPNs, plus domain routes in priority order (first match wins).
 * `blockIpv6`: a VPN carries all traffic. No VPN carries IPv6, so it's refused instead of leaving outside them.
 */
export const HostRoutes = z
  .strictObject({
    tunnels: z.array(VpnTunnelInput).max(64),
    domains: z.array(DomainRouteInput).max(1024),
    blockIpv6: z.boolean(),
    stats: StatsEndpointInput.optional(),
  })
  .refine((routes) => routes.domains.every((route) => routes.tunnels.some((tunnel) => tunnel.vpnId === route.vpnId)), {
    message: "Domain route for a VPN that isn't connected",
    path: ['domains'],
  });
export type HostRoutes = z.infer<typeof HostRoutes>;

/** Nothing routed: what the helper applies when a session ends. */
export const NO_ROUTES: HostRoutes = { tunnels: [], domains: [], blockIpv6: false };

export const HelperRequest = z.discriminatedUnion('command', [
  z.strictObject({ command: z.literal('status') }),
  z.strictObject({ command: z.literal('hello'), nonce: Token }),
  z.strictObject({ command: z.literal('auth'), proof: Hex64 }),
  /** Replaces the whole routing state. No tunnels removes all routes and DNS entries. */
  z.strictObject({ command: z.literal('apply'), routes: HostRoutes }),
]);
export type HelperRequest = z.infer<typeof HelperRequest>;

export const HelperResponse = z.discriminatedUnion('ok', [
  z.object({ ok: z.literal(true), version: z.number().int(), challenge: Token.optional(), proof: Hex64.optional() }),
  z.object({ ok: z.literal(false), error: z.string() }),
]);
export type HelperResponse = z.infer<typeof HelperResponse>;

/** The helper's answer to `hello`: its challenge for the app, and proof that it holds the key. */
export const HelloReply = z.object({ ok: z.literal(true), version: z.number().int(), challenge: Token, proof: Hex64 });

/** Parses one line as a request; never throws. */
export function parseHelperLine(line: string): { ok: true; request: HelperRequest } | { ok: false; error: string } {
  let json: unknown;
  try {
    json = JSON.parse(line);
  } catch {
    return { ok: false, error: 'Malformed request' };
  }
  const parsed = HelperRequest.safeParse(json);
  if (!parsed.success) {
    const issue = parsed.error.issues[0];
    return { ok: false, error: `${issue?.path.join('.') || 'request'}: ${issue?.message ?? 'invalid'}` };
  }
  return { ok: true, request: parsed.data };
}
